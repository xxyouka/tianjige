function getBirthdayFlower(month, day) {
  const dateStr = `${month.toString().padStart(2, '0')}-${day.toString().padStart(2, '0')}`
  return BIRTHDAY_FLOWERS.find(f => f.date === dateStr) || BIRTHDAY_FLOWERS[0]
}

router.post('/lookup', async (req, res) => {
  try {
    const { month, day } = req.body

    const m = parseInt(month)
    const d = parseInt(day)
    if (isNaN(m) || isNaN(d) || m < 1 || m > 12 || d < 1 || d > 31) {
      return res.status(400).json({ error: '请输入有效的生日' })
    }

    const flowerData = getBirthdayFlower(m, d)

    const interpretation = await askAI(
      flowerPrompt.system,
      flowerPrompt.buildUserMessage({ flowerData, month: m, day: d })
    )

    res.json({
      data: flowerData,
      interpretation
    })
  } catch (err) {
    console.error('生日花语错误:', err)
    res.status(500).json({ error: '查询出错，请稍后重试' })
  }
})

